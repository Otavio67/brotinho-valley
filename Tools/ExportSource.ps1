$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$sourceRoot = Join-Path $projectRoot 'Assets'
$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('# Complete project C# source')
[void]$builder.AppendLine('')
[void]$builder.AppendLine('Generated by Tools/ExportSource.ps1. Runtime, editor tooling and tests are also available as individual .cs files at the paths shown below. Third-party package source is excluded.')
$files = Get-ChildItem -LiteralPath $sourceRoot -Recurse -Filter '*.cs' | Sort-Object FullName
foreach ($file in $files) {
    $relative = [System.IO.Path]::GetRelativePath($projectRoot, $file.FullName).Replace('\','/')
    [void]$builder.AppendLine('')
    [void]$builder.AppendLine('## ' + $relative)
    [void]$builder.AppendLine('')
    [void]$builder.AppendLine('```csharp')
    [void]$builder.AppendLine([System.IO.File]::ReadAllText($file.FullName).TrimEnd())
    [void]$builder.AppendLine('```')
}
[System.IO.File]::WriteAllText((Join-Path $projectRoot 'Docs\SOURCE_CODE.md'), $builder.ToString())
Write-Output ('Exported ' + $files.Count + ' C# files to Docs/SOURCE_CODE.md')
